"""Checks on the ingredient table (backend/app/data/ingredients.json) that the diet plans are built from.

The table is generated by evaluation/build_ingredients.py (IFCT 2017) and evaluation/usda_values.py (USDA SR Legacy).
These tests pin unit conversions to values printed in IFCT 2017 and guard diet, allergen and data-quality rules.
"""
import json
from pathlib import Path

import pytest

DATA = json.loads((Path(__file__).resolve().parents[1] / "app" / "data" / "ingredients.json").read_text(encoding="utf-8"))
FOODS = {f["code"]: f for f in DATA["ingredients"]}
SEAFOOD_GROUPS = {"Marine Fish", "Fresh Water Fish and Shellfish", "Marine Shellfish", "Marine Mollusks"}


def test_every_ifct_food_and_kitchen_ingredient_is_present():
    ifct = [c for c in FOODS if not c.startswith("X")]
    assert len(ifct) == 542 and len(FOODS) == len(DATA["ingredients"])
    assert {"X001", "X003", "X004", "X016", "X018"} <= set(FOODS)


@pytest.mark.parametrize("code, key, expected", [
    ("A003", "iron_mg", 6.42),          # bajra, IFCT 2017
    ("A010", "calcium_mg", 364.0),      # ragi
    ("A015", "energy_kcal", 356),       # rice, raw, milled
    ("A003", "energy_kcal", 348),       # bajra
    ("C022", "iron_mg", 7.65),          # gongura (gogu leaves, green stem)
])
def test_units_are_converted_correctly(code, key, expected):
    assert FOODS[code]["per_100g"][key] == pytest.approx(expected, abs=0.01)


def test_no_food_is_missing_its_energy():
    zero = [f["name"] for f in FOODS.values() if f["per_100g"]["energy_kcal"] == 0 and f["code"] != "X004"]
    assert not zero, zero
    assert FOODS["T013"]["per_100g"]["energy_kcal"] == 884  # ghee: 100 g fat x 37 kJ/g


def test_energy_agrees_with_the_macronutrients():
    """IFCT energy should be close to what protein, fat, carbohydrate and fibre give (IFCT energy factors).
    Lemon juice is the one known exception: its energy includes citric acid, which is not counted as carbohydrate."""
    for f in FOODS.values():
        if f["code"].startswith("X") or f["code"] == "E033":
            continue
        p = f["per_100g"]
        from_macros = (p["protein_g"] * 17 + p["fat_g"] * 37 + p["carbs_g"] * 17 + p["fibre_g"] * 8) / 4.184
        if from_macros > 15:
            assert 0.65 <= p["energy_kcal"] / from_macros <= 1.6, (f["code"], f["name"], p["energy_kcal"])


def test_chicken_leg_energy_entry_error_is_corrected():
    leg = FOODS["N001"]
    assert leg["per_100g"]["energy_kcal"] == 191  # IFCT lists 1605 kJ; protein and fat give about 800 kJ
    assert any("1605 kJ" in note for note in leg["notes"])


def test_values_are_in_plausible_ranges():
    for f in FOODS.values():
        p = f["per_100g"]
        assert 0 <= p["energy_kcal"] <= 902, f["name"]  # pure oils: 900-902 kcal in USDA
        assert 0 <= p["protein_g"] + p["fat_g"] + p["carbs_g"] + p["fibre_g"] <= 101, f["name"]
        assert 0 <= p["iron_mg"] <= 120 and 0 <= p["calcium_mg"] <= 2000 and 0 <= p["folate_ug"] <= 1500, f["name"]  # liver is the richest source (about 1,000 ug)


def test_diet_types():
    assert FOODS["L002"]["diet"] == FOODS["L003"]["diet"] == FOODS["T013"]["diet"] == "vegetarian"  # milk, paneer, ghee
    assert FOODS["M001"]["diet"] == "eggetarian"
    assert FOODS["N003"]["diet"] == FOODS["S006"]["diet"] == "non_veg"
    assert FOODS["A015"]["diet"] == FOODS["B001"]["diet"] == "vegan"
    for f in FOODS.values():
        if f["animal_source"] != "none":
            assert f["diet"] != "vegan", f["name"]


@pytest.mark.parametrize("code, allergen", [
    ("H012", "nuts"), ("T005", "nuts"), ("H009", "sesame"), ("T004", "sesame"), ("A019", "gluten"), ("A022", "gluten"),
    ("B025", "soy"), ("M001", "eggs"), ("S008", "seafood"), ("T013", "dairy"), ("X001", "dairy"), ("X016", "dairy"),
])
def test_allergens(code, allergen):
    assert allergen in FOODS[code]["allergens"]


def test_every_seafood_is_marked_seafood():
    for f in FOODS.values():
        if f["group"] in SEAFOOD_GROUPS:
            assert "seafood" in f["allergens"], f["name"]


def test_vitamin_b12_and_d():
    for f in FOODS.values():
        p = f["per_100g"]
        if f["animal_source"] == "none" and f["group"] != "Mushrooms" and f["code"] not in ("X017", "X024"):  # X024 fortified
            assert p["vitamin_b12_ug"] == 0 and p["vitamin_d_iu"] == 0, f["name"]
    assert FOODS["M001"]["per_100g"]["vitamin_b12_ug"] == 0.89  # hen's egg, USDA exact match
    assert FOODS["X018"]["per_100g"]["vitamin_d_iu"] == 20.0  # fortified milk at the FSSAI minimum
    assert FOODS["A010"]["per_100g"]["vitamin_d_iu"] == 0  # ragi: IFCT's vitamin D is not used


def test_uncertain_values_are_flagged():
    assert FOODS["S006"]["uncertain"] == ["vitamin_d_iu"]  # rohu matched to carp
    assert FOODS["X017"]["uncertain"] == ["vitamin_d_iu"]  # sun-exposed mushrooms
    approximate = [f for f in FOODS.values() if f.get("b12_vitamin_d_source", {}).get("match") == "approximate"
                   and f["group"] == "Marine Fish"]
    assert approximate and all(f["uncertain"] == ["vitamin_b12_ug", "vitamin_d_iu"] for f in approximate)


def test_regional_names():
    assert FOODS["A003"]["names"]["te"] == "Sajjalu" and FOODS["A003"]["names"]["hi"] == "Bajra"
    assert FOODS["C022"]["names"]["te"] == "Gongura"
    assert sum("te" in f["names"] for f in FOODS.values()) >= 450


def test_alcohol_is_never_used_in_plans():
    assert FOODS["K001"]["usable_in_plans"] is False
