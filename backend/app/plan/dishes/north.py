def tadka(fat_g, fat="ghee", cumin=0.5, hing=0.05, red_chilli=0.5, garlic=0):
    """North Indian tadka: ghee or oil with cumin, hing and red chilli; every part is fried."""
    parts = [(fat, fat_g), ("cumin seeds", cumin), ("asafoetida", hing), ("dry red chilli", red_chilli),
             ("garlic", garlic)]
    return [(name, grams, "frying") for name, grams in parts if grams > 0]


